class _EmptyApi extends ApiClient {
  _EmptyApi()
    : super(
        AppConfig.forLocalServer('http://127.0.0.1:3210/api/v1'),
        FakeTokenStore(),
      );

  @override
  Future<List<Map<String, dynamic>>> getList(
    String path, {
    Map<String, dynamic>? query,
  }) async => const [];
}

const _user = AppUser(
  id: 'u',
  username: 'u',
  fullName: 'User',
  companyId: 'c',
  branchId: 'b',
  isSuperAdmin: true,
);

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  for (final kind in InvoiceKind.values) {
    testWidgets('an empty ${kind.name} invoice list says what to do next', (
      tester,
    ) async {
      tester.view.physicalSize = const Size(1700, 1000);
      tester.view.devicePixelRatio = 1;
      addTearDown(tester.view.resetPhysicalSize);
      addTearDown(tester.view.resetDevicePixelRatio);
      await tester.pumpWidget(
        ProviderScope(
          overrides: [
            apiClientProvider.overrideWithValue(_EmptyApi()),
            currentUserProvider.overrideWithValue(_user),
            exportCapabilitiesProvider.overrideWith(
              (ref) async => ExportCapabilities.unknown,
            ),
          ],
          child: MaterialApp(
            locale: const Locale('en'),
            localizationsDelegates: AppLocalizations.localizationsDelegates,
            supportedLocales: AppLocalizations.supportedLocales,
            home: Scaffold(body: InvoiceListScreen(kind: kind)),
          ),
        ),
      );
      await tester.pumpAndSettle();

      expect(
        find.textContaining(
          kind.isSales
              ? 'No sales invoices yet. Choose'
              : 'No purchase invoices yet. Choose',
        ),
        findsOneWidget,
      );
      expect(tester.takeException(), isNull);
    });
  }
}
